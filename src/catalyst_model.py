"""
PDH (Propane DeHydrogenation) シミュレータ — 触媒活性モデルモジュール

本モジュールは、プロパン脱水素プロセスにおける触媒活性パラメータ ``a`` を
温度と運転時間から計算する関数を提供する。

採用手法：2次元スプライン補間（RectBivariateSpline）
    - 数式フィッティングは一切使用しない
    - `data/a_parameter_fitting.xlsx` の 0〜30 分データをハードコードして初期化
    - データ点上での誤差ゼロを保証（s=0 オプション）
    - 入力・出力ともにクリッピングによりシミュレータの発散を防止

参考：補間の詳細は monitor/fitting_analysis.ipynb を参照。

コンテスト要項 §3-3 に「a については最高温度（触媒層入口温度）と運転時間により
決定するものとする」と明記されている。
このため、シミュレーション内で触媒層の空間方向ごとに逐次 a を計算するのではなく、
触媒層入口温度（= 触媒層内の最高温度）をもとに a を一律で決定する仕様とする。
出典: 第17回プロセスデザイン学生コンテスト要項 §3-3

触媒モデルの整合性 (2026-05-19 確定):
    要項 §3-3 の a データ自体は「架空触媒」のものとして提供されているが、
    その挙動 (700°C で 30 min で a≈0.04 と分単位で急速失活、400°C で a≈0.81)
    は工業 Cr2O3-Al2O3 触媒 (Catofin プロセス) の物理と整合する。Pt-Sn 系
    (UOP Oleflex) は CCR 連続再生方式で日〜週オーダーの緩慢失活であり、
    分単位失活と本実装のスイング再生 (t_regen=30 min) には不整合。
    よって反応器の経済パラメータ (単価/寿命/bulk density) は Cr2O3 系の
    文献値を採用する。詳細: units/reactors/swing.py ヘッダ、KNOWN_PLACEHOLDERS.md §A.4
"""

import warnings

import numpy as np
from scipy.interpolate import RectBivariateSpline

# ---------------------------------------------------------------------------
# ハードコードされたグリッドデータ
# （出典: data/a_parameter_fitting.xlsx の 0〜30 分範囲）
# ---------------------------------------------------------------------------

# 温度軸 [°C]（厳密昇順）
_T_ARR: np.ndarray = np.array(
    [400.0, 450.0, 500.0, 550.0, 600.0, 650.0, 700.0],
    dtype=float,
)

# 時間軸 [min]（厳密昇順）
_t_ARR: np.ndarray = np.array(
    [0.0, 5.0, 10.0, 15.0, 20.0, 25.0, 30.0],
    dtype=float,
)

# 活性マトリクス: _A_MATRIX[i, j] = a( _T_ARR[i], _t_ARR[j] )
# 行 = 温度インデックス (400〜700 °C)
# 列 = 時間インデックス (0〜30 min)
_A_MATRIX: np.ndarray = np.array(
    [
        #  t=0     t=5    t=10   t=15   t=20   t=25   t=30
        [1.000,  0.940, 0.900, 0.860, 0.840, 0.820, 0.810],  # 400 °C
        [1.000,  0.870, 0.800, 0.760, 0.720, 0.700, 0.680],  # 450 °C
        [1.000,  0.800, 0.680, 0.622, 0.570, 0.520, 0.490],  # 500 °C
        [1.000,  0.670, 0.520, 0.420, 0.360, 0.310, 0.280],  # 550 °C
        [1.000,  0.520, 0.350, 0.240, 0.180, 0.150, 0.130],  # 600 °C
        [1.000,  0.380, 0.210, 0.130, 0.090, 0.070, 0.060],  # 650 °C
        [1.000,  0.250, 0.120, 0.080, 0.060, 0.050, 0.040],  # 700 °C
    ],
    dtype=float,
)

# ---------------------------------------------------------------------------
# スプラインオブジェクトのモジュール読み込み時インスタンス化
# （関数呼び出しのたびに再構築するコストを避けるため、モジュール変数として保持）
# ---------------------------------------------------------------------------

_spline = RectBivariateSpline(
    _T_ARR,     # x 軸：温度 [°C]
    _t_ARR,     # y 軸：時間 [min]
    _A_MATRIX,  # z：活性値マトリクス
    kx=3,       # 温度方向の次数：3次スプライン
    ky=3,       # 時間方向の次数：3次スプライン
    # s=0 はデフォルト（スムージングなし = 全データ点を厳密に通過）
)

# ---------------------------------------------------------------------------
# 入力・出力の有効範囲（クリッピング用）
# ---------------------------------------------------------------------------

_T_MIN, _T_MAX = 400.0, 700.0   # 温度の有効範囲 [°C]
_t_MIN, _t_MAX = 0.0,   30.0    # 時間の有効範囲 [min]
_A_MIN, _A_MAX = 0.0,   1.0     # 活性の物理的上下限 [-]


# ---------------------------------------------------------------------------
# 公開関数
# ---------------------------------------------------------------------------

def calculate_activity_a(T_celsius: float, t_min: float) -> float:
    """
    触媒活性パラメータ ``a`` を温度と経過時間から計算する。

    2次元スプライン補間（RectBivariateSpline, kx=3, ky=3）を用いて
    データ点上での誤差ゼロを保証する。

    モデルのデータ源
    ----------------
    ``data/a_parameter_fitting.xlsx`` の 0〜30 分データをハードコード。
    補間の詳細は ``monitor/fitting_analysis.ipynb`` を参照。

    安全処理（シミュレータ発散防止）
    ---------------------------------
    入力のクリッピング
        - 温度：400〜700 °C の範囲に制限（外挿禁止）
        - 時間：0〜30 min の範囲に制限（外挿禁止）
    出力のクリッピング
        - 活性：0.0〜1.0 の物理的範囲に制限

    Parameters
    ----------
    T_celsius : float
        反応温度 [°C]。
        有効範囲の目安：400〜700 °C（データ範囲外は端値にクリップされる）。
    t_min : float
        触媒の経過運転時間 [min]。
        有効範囲：0〜30 min（データ範囲外は端値にクリップされる）。

    Returns
    -------
    float
        触媒活性パラメータ ``a`` [-]。常に [0.0, 1.0] の範囲に収まる。
        新鮮な触媒（t=0）では 1.0、失活が進むほど 0 に近づく。

    Examples
    --------
    >>> # 600 °C で 15 分運転後の触媒活性（データ点上の値）
    >>> round(calculate_activity_a(600.0, 15.0), 10)
    0.24

    >>> # 初期状態（t=0）はすべての温度で 1.0
    >>> calculate_activity_a(700.0, 0.0)
    1.0

    >>> # 範囲外入力は端値にクリップされる（シミュレータ安全処理）
    >>> round(calculate_activity_a(750.0, 50.0), 6) == round(calculate_activity_a(700.0, 30.0), 6)
    True
    """
    # 範囲外チェック（クリップ前に警告）
    if not (_T_MIN <= T_celsius <= _T_MAX):
        warnings.warn(
            f"calculate_activity_a: T_celsius={T_celsius:.2f} °C は有効範囲 "
            f"[{_T_MIN}, {_T_MAX}] °C 外です。端値にクリップして計算を続行します。",
            UserWarning,
            stacklevel=2,
        )
    if not (_t_MIN <= t_min <= _t_MAX):
        warnings.warn(
            f"calculate_activity_a: t_min={t_min:.2f} min は有効範囲 "
            f"[{_t_MIN}, {_t_MAX}] min 外です。端値にクリップして計算を続行します。",
            UserWarning,
            stacklevel=2,
        )

    # 入力クリッピング：スプラインの外挿領域に踏み込まないよう制限
    T_clipped = float(np.clip(T_celsius, _T_MIN, _T_MAX))
    t_clipped = float(np.clip(t_min,     _t_MIN, _t_MAX))

    # スプライン評価
    # _spline(T, t) はグリッド評価（2D配列）を返すため、スカラー評価には ev() を使用する。
    # ev(xi, yi) は点ごとの評価を行い 1D配列を返すので [0] でスカラーを取り出す。
    a_raw = float(_spline.ev(np.array([T_clipped]), np.array([t_clipped]))[0])

    # 出力クリッピング：物理的に a は必ず [0, 1] に収める
    return float(np.clip(a_raw, _A_MIN, _A_MAX))
