# ---------------------------------------------------------------------------
# 定圧比熱 (代表値、300〜600 K 範囲の粗近似) [J/(mol·K)]
# !仮置き — 要出典: NIST Shomate 多項式または DIPPR データから温度依存性を含む
#                 関数形に置換 (現状は範囲平均の固定値のため反応器高温域で誤差大)
# 設計判断: 厳密な温度依存性は無視。反応器・冷却器・ミキサーのいずれも
#          ±5% 程度の誤差で済む簡略近似で十分 (fake_columnX が支配的なため)。
#          サロゲート蒸留塔が来たらここの精度も再検討する。
# ---------------------------------------------------------------------------
CP_J_PER_MOL_K: Dict[str, float] = {
    'A': 100.0,   # C3H8
    'B':  90.0,   # C3H6
    'C':  29.0,   # H2
    'D':  55.0,   # C2H4
    'E':  38.0,   # CH4
    'F':  70.0,   # C2H6
    'Z': 130.0,   # C4H10
}
CP_DEFAULT: float = 60.0   # 不明成分のフォールバック値


# ---------------------------------------------------------------------------
# 標準沸点 (1 atm) [K]
# 設計判断: cooler の相変化判定や、ターゲット温度との比較に使う。
#          高圧下では泡点・露点が変動するが、現状の dummy ユニットでは
#          1 atm 沸点を「相が変わる温度の目安」として使用する。
# ---------------------------------------------------------------------------
BOILING_POINT_K: Dict[str, float] = {
    'A': 231.05,   # C3H8 (-42.1°C)
    'B': 225.46,   # C3H6 (-47.7°C)
    'C':  20.39,   # H2  (-252.8°C)
    'D': 169.42,   # C2H4 (-103.7°C)
    'E': 111.66,   # CH4 (-161.5°C)
    'F': 184.55,   # C2H6 (-88.6°C)
    'Z': 272.65,   # C4H10 (-0.5°C; n-butane)
}


# ---------------------------------------------------------------------------
# 蒸発潜熱 (沸点における) [kJ/kmol]
# !仮置き — 要出典: 沸点での ΔH_vap を使用中。実際の動作圧力下での値は
#                 Watson 式 (ΔH_vap ∝ (1-Tr)^0.38) 等で温度補正すべき
# 出典 (現状): NIST WebBook, 各成分の沸点における ΔH_vap
# 設計判断: cooler.py で相変化を伴う計算 (例: mem_precool で液→気) を
#          扱うために用意。温度依存性は無視 (沸点における代表値で固定)。
# ---------------------------------------------------------------------------
LATENT_HEAT_KJ_PER_KMOL: Dict[str, float] = {
    'A': 19000.0,   # C3H8  (453 J/g × 44.1)
    'B': 18400.0,   # C3H6  (437 J/g × 42.08)
    'C':   904.0,   # H2    (448 J/g × 2.02)
    'D': 13560.0,   # C2H4  (483 J/g × 28.05)
    'E':  8200.0,   # CH4   (511 J/g × 16.04)
    'F': 14700.0,   # C2H6  (489 J/g × 30.07)
    'Z': 22440.0,   # C4H10 (386 J/g × 58.12)
}


def cp_of(component: str) -> float:
    """成分キーから Cp を取得。未知成分は CP_DEFAULT。"""
    return CP_J_PER_MOL_K.get(component, CP_DEFAULT)


def cp_mix(F_in: Dict[str, float]) -> float:
    """組成 F_in [kmol/h] のモル流量加重平均 Cp [J/(mol·K)]。"""
    total = sum(F_in.values())
    if total <= 0.0:
        return CP_DEFAULT
    return sum(F_in.get(k, 0.0) * cp_of(k) for k in F_in) / total
